_BY_ABBREV = {abbrev: abbrev for abbrev in STATE_ABBREVIATIONS.values()}
_BY_NAME = {name.lower(): abbrev for name, abbrev in STATE_ABBREVIATIONS.items()}


def state_code(value: str | None) -> str | None:
    """Return a two-letter code for a state name or abbreviation."""

    if not value:
        return None
    text = value.strip()
    if not text:
        return None
    upper = text.upper()
    if upper in _BY_ABBREV:
        return upper
    return _BY_NAME.get(text.lower())
